"""Writes the day's reports to files, and optionally e-mails them: run it every evening from a scheduler.

    manage.py generate_daily_reports                      today, every project
    manage.py generate_daily_reports --date 2026-11-01    a past day
    manage.py generate_daily_reports --project AB-PRJ-001 one project only

Per project and day it writes, under REPORTS_DIR/<project code>/<date>/:
    daily_transactions_<code>_<date>.pdf and .xlsx   every transaction of the day, verified or not
    daily_costs_<code>_<date>.pdf                    the day's cost, pre-development and post-development apart
    profitability_<code>_<date>.pdf                  the profitability analysis as of that day's run
"""
import datetime
from pathlib import Path

from django.conf import settings
from django.core.mail import EmailMessage
from django.core.management.base import BaseCommand, CommandError
from django.utils import timezone

from projects.models import Development
from reports.costs import daily_cost_report
from reports.daily import daily_transactions_report, day_book, parse_day, period_text
from reports.excel import build_xlsx
from reports.profitability import profitability_report
from reports.tables import build_pdf


class AutomaticUser:
    """Stands in for a person in the "Generated by" line of the files."""

    username = 'automatic'

    def get_full_name(self):
        return 'Automatic report'


class Command(BaseCommand):
    help = 'Writes (and optionally e-mails) the daily transactions report and the profitability analysis of each project.'

    def add_arguments(self, parser):
        parser.add_argument('--date', help='The day to report, YYYY-MM-DD. Default: today.')
        parser.add_argument('--project', help='Only this project (its code, e.g. AB-PRJ-001). Default: every project.')
        parser.add_argument('--output', help='Folder to write to. Default: REPORTS_DIR from the settings.')
        parser.add_argument('--include-empty', action='store_true', help='Also write the report of a project with no transactions that day.')
        parser.add_argument('--skip-profitability', action='store_true', help='Do not write the profitability analysis.')
        parser.add_argument('--no-email', action='store_true', help='Write the files but do not e-mail them.')

    def handle(self, *args, **options):
        day = parse_day(options['date'], None) if options['date'] else timezone.localdate()
        if day is None:
            raise CommandError('--date must look like 2026-11-01.')
        root = Path(options['output'] or settings.REPORTS_DIR)
        projects = Development.objects.all()
        if options['project']:
            projects = projects.filter(code=options['project'])
            if not projects:
                raise CommandError(f'No project has the code {options["project"]}.')

        written = []
        for development in projects:
            written += self.report_project(development, day, root, options)
        self.stdout.write(self.style.SUCCESS(f'{len(written)} file(s) written to {root}.'))

    def report_project(self, development, day, root, options):
        book = day_book(development, day, day)
        if not book['entries'] and not options['include_empty']:
            self.stdout.write(f'{development.code}: no transactions on {day:%d %b %Y}, nothing written.')
            return []

        folder = root / development.code / f'{day:%Y-%m-%d}'
        folder.mkdir(parents=True, exist_ok=True)
        stamp = f'{development.code}_{day:%Y-%m-%d}'
        user = AutomaticUser()
        files = []

        lines, tables = daily_transactions_report(development, day, day, book)
        title = 'Daily Transactions'
        pdf, xlsx = folder / f'daily_transactions_{stamp}.pdf', folder / f'daily_transactions_{stamp}.xlsx'
        with open(pdf, 'wb') as handle:
            build_pdf(handle, title, lines, tables, user)
        with open(xlsx, 'wb') as handle:
            build_xlsx(handle, title, lines, tables, user)
        files += [pdf, xlsx]

        c_lines, c_tables = daily_cost_report(None, development, day, day)
        costs_pdf = folder / f'daily_costs_{stamp}.pdf'
        with open(costs_pdf, 'wb') as handle:
            build_pdf(handle, 'Daily Cost Report', c_lines, c_tables, user)
        files.append(costs_pdf)

        if not options['skip_profitability']:
            p_lines, p_tables = profitability_report(None, development)
            profit = folder / f'profitability_{stamp}.pdf'
            with open(profit, 'wb') as handle:
                build_pdf(handle, 'Profitability Analysis', p_lines, p_tables, user)
            files.append(profit)

        for path in files:
            self.stdout.write(f'{development.code}: {path}')
        if not options['no_email']:
            self.email(development, day, book, files)
        return files

    def email(self, development, day, book, files):
        recipients = list(settings.REPORT_RECIPIENTS)
        if not recipients:
            return
        body = (
            f'{development.name} - {period_text(day, day)}\n\n'
            f'{len(book["entries"])} transaction(s): money in {book["money_in"]:,.2f}, money out {book["money_out"]:,.2f}.\n'
            f'{book["verified"]} verified, {book["pending"]} still to be verified.\n\n'
            'The reports are attached. They were generated automatically.'
        )
        message = EmailMessage(f'Daily report {development.code} {day:%d %b %Y}', body, settings.DEFAULT_FROM_EMAIL, recipients)
        for path in files:
            message.attach_file(str(path))
        try:
            message.send()
            self.stdout.write(f'{development.code}: e-mailed to {", ".join(recipients)}.')
        except Exception as error:   # a mail problem must not lose the files that were just written
            self.stderr.write(f'{development.code}: the e-mail could not be sent ({error}).')
